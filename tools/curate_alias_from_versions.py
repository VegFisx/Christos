def main() -> int:
    d = json.loads(SRC.read_text(encoding="utf-8"))
    cands = d["candidates"][:100]
    adopted, rows = [], []
    for i, x in enumerate(cands, 1):
        verdict, why, hint = JUDGE.get(i, ("否决", "未逐条判（默认否决，宁缺毋滥）", ""))
        rows.append({"序号": i, "异名": x["alias"], "表里建议": x["canonical"],
                     "判定": verdict, "理由": why, "修正建议": hint,
                     "票数": x["votes"], "置信度": x["confidence"],
                     "例子": "、".join(x.get("examples") or [])})
        if verdict == "采纳":
            adopted.append({"alias": x["alias"], "canonical": x["canonical"],
                            "why": why, "source": "mine_alias_from_versions + 人工判定(2026-10-17)",
                            "votes": x["votes"], "confidence": x["confidence"]})
    with open(OUT_CSV, "w", encoding="utf-8-sig", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)
    # ★ 追加用户确认的 18 条（不在 Top100 表里，单独记，来源写明"用户确认"）
    for a, b, why in USER_CONFIRMED:
        adopted.append({"alias": a, "canonical": b, "why": why,
                        "source": "用户确认(2026-10-17)", "votes": None, "confidence": None})
    json.dump({"n": len(adopted), "note": "只含人工判定为『采纳』的项；炮制品/加工品一律不替换",
               "pairs": adopted}, open(OUT_JSON, "w", encoding="utf-8"),
              ensure_ascii=False, indent=1)
    n_ok = sum(1 for r in rows if r["判定"] == "采纳")
    n_no = sum(1 for r in rows if r["判定"] == "否决")
    print("Top100 判定：采纳 %d ｜ 否决 %d" % (n_ok, n_no))
    print("  审定表共 %d 条（Top100 采纳 %d + 用户确认 %d）"
          % (len(adopted), n_ok, len(USER_CONFIRMED)))
    print("  采纳清单：%s" % "、".join("%s→%s" % (a["alias"], a["canonical"])
                                       for a in adopted[:16]) + " …")
    print("  -> %s" % OUT_JSON)
    print("  -> %s" % OUT_CSV)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
